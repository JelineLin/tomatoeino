func TestPostgresQueryQualifiesTablesAndRebindsParameters(t *testing.T) {
	store := &Store{dialect: dialectPostgres}
	got := store.query(`SELECT * FROM lessons l JOIN reading_attempts r ON r.lesson_id=l.id WHERE l.user_id=? AND r.id>?`)
	want := `SELECT * FROM english.lessons l JOIN english.reading_attempts r ON r.lesson_id=l.id WHERE l.user_id=$1 AND r.id>$2`
	if got != want {
		t.Fatalf("query = %q, want %q", got, want)
	}
}

func TestDatabaseDateAndTimeScanBothBackends(t *testing.T) {
	var date databaseDate
	if err := date.Scan(time.Date(2026, 9, 10, 0, 0, 0, 0, time.UTC)); err != nil || date != "2026-09-10" {
		t.Fatalf("PostgreSQL date scan = %q, %v", date, err)
	}
	var timestamp databaseTime
	if err := timestamp.Scan("2026-09-10T08:09:10.123Z"); err != nil || timestamp.UTC().Format(time.RFC3339Nano) != "2026-09-10T08:09:10.123Z" {
		t.Fatalf("SQLite timestamp scan = %v, %v", timestamp.Time, err)
	}
}

func TestEnglishPostgresMigrationCoversUserTables(t *testing.T) {
	raw, err := os.ReadFile("../../migrations/postgres/000004_english_business_data.up.sql")
	if err != nil {
		t.Fatal(err)
	}
	sql := string(raw)
	for _, table := range userScopedTables {
		if !strings.Contains(sql, "CREATE TABLE english."+table) {
			t.Errorf("PostgreSQL migration 缺少 %s", table)
		}
	}
	for _, guard := range []string{
		"FOREIGN KEY (lesson_id, user_id)",
		"FOREIGN KEY (speaking_attempt_id, user_id)",
		"GENERATED BY DEFAULT AS IDENTITY",
		"REFERENCES account.users(id) ON DELETE CASCADE",
	} {
		if !strings.Contains(sql, guard) {
			t.Errorf("PostgreSQL migration 缺少约束 %q", guard)
		}
	}
}

